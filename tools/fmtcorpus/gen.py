"""gen.py [--record --tiko <exe>] -- the shared format-string corpus, written as two tests.

docs/tiko-strings/RFC-0002-format.md section 7.1: the format-string parser exists twice, once in
std/strings (pkg/std/strings/formatimpl.tiko) and once in the compiler (src/symbols/formatcheck.tiko).
corpus.txt holds the cases; this writes them as

    tests/std/format/corpus.tiko + .test        strings.TryFormat over each case, at run time:
                                                the code and the offset must be the expected ones
    tests/diagnostics/src/format-check.tiko     strings.Format over each case, compiled: every
    tests/diagnostics/format-check.test         refusal the compiler can see is reported with the
                                                same code's TKO id, at the column of the same
                                                offset, and nothing else is reported

so neither parser can change without the other's test saying so.

--record runs the run-time test once with <exe> and REWRITES each case's expectation in
corpus.txt with what TryFormat answered (a 'run' mark is kept). Review the diff: it is the spec.
Run from the repository root.
"""
import os
import re
import subprocess
import sys
import unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))
CORPUS = os.path.join(HERE, "corpus.txt")

CODES = ["NONE", "UNMATCHED_OPEN", "UNMATCHED_CLOSE", "BAD_ARG_ID", "MIXED_INDEXING",
         "MISSING_ARG", "BAD_SPEC", "BAD_FILL", "BAD_TYPE", "BAD_MODIFIER", "PRECISION",
         "DYNAMIC_NOT_INT", "DYNAMIC_NEGATIVE", "LOCALE", "CHAR_RANGE", "NULL_CSTRING", "CUSTOM"]
# The compiler's id for each code it can see (diagids.ti: TKO0847.. in FormatErrorCode order).
TKO = {"UNMATCHED_OPEN": "TKO0847", "UNMATCHED_CLOSE": "TKO0848", "BAD_ARG_ID": "TKO0849",
       "MIXED_INDEXING": "TKO0850", "MISSING_ARG": "TKO0851", "BAD_SPEC": "TKO0852",
       "BAD_FILL": "TKO0853", "BAD_TYPE": "TKO0854", "BAD_MODIFIER": "TKO0855",
       "PRECISION": "TKO0856", "DYNAMIC_NOT_INT": "TKO0857", "LOCALE": "TKO0858"}

PRELUDE = '''#import "std/strings"
type Money extends strings.Formattable
    as longint cents
    declare function FormatWith( byref spec as const ustring, byref ctx as strings.FormatContext ) as ustring override
end type
function Money.FormatWith( byref spec as const ustring, byref ctx as strings.FormatContext ) as ustring
    if spec = "!" then
        ctx.SetError( "Money takes no '!'" )
        return ""
    end if
    return "m" & spec
end function
type Named
    as string nm
    declare operator cast( ) as string
end type
operator Named.cast( ) as string
    return nm
end operator
enum Color
    Red
    Green
end enum
dim as ustring who = "Quinn"
dim as long i = 42
dim as double d = 3.25
dim as single sg = 1.5
dim as boolean b = true
dim as zstring ptr z = @"zed"
dim as zstring ptr nz = 0
dim as any ptr p = cast( any ptr, &h1234 )
dim as ubyte ub = 200
dim as short sh = -5
dim as uinteger ui = 77
dim as Color col = Green
dim as Money m
m.cents = 1
dim as Named nn
nn.nm = "named"
dim as strings.FormatArg fa = strings.FormatArg( 1 )
'''


def load():
    cases = []
    lines = open(CORPUS, encoding="utf-8").read().split("\n")
    for n, ln in enumerate(lines):
        if not ln.strip() or ln.startswith("#"):
            continue
        parts = [x.strip() for x in ln.rsplit("|", 2)]
        assert len(parts) == 3, (n + 1, ln)
        lit, args, exp = parts
        ex = exp.split()
        code = ex[0]
        off = int(ex[1]) if len(ex) > 1 else 0
        run = len(ex) > 2 and ex[2] == "run"
        assert code == "OK" or code in CODES, (n + 1, code)
        cases.append(dict(line=n, lit=lit, args=args, code=code, off=off, run=run))
    return lines, cases


def call(fn, c):
    return "strings.%s( %s%s )" % (fn, c["lit"], (", " + c["args"]) if c["args"] else "")


def runtime_test(cases):
    out = ["'' GENERATED by tools/fmtcorpus/gen.py from tools/fmtcorpus/corpus.txt -- edit those, not this.",
           "'' std/strings TryFormat over the shared format-string corpus: each case's code and offset.",
           "#import \"std/outcome\""]
    out += PRELUDE.rstrip("\n").split("\n")
    out += ["dim shared as long passed, failed",
            "sub Expect( byref r as outcome.Result( of ustring, strings.FormatError ), byval code as long, byval off as integer, byval ln as long )",
            "    dim as long gc = 0",
            "    dim as integer go = 0",
            "    if r.IsOk( ) = false then gc = r.Failure( ).code : go = r.Failure( ).offset",
            "    if (gc = code) andalso ((code = 0) orelse (go = off)) then",
            "        passed += 1",
            "    else",
            "        failed += 1",
            "        print \"corpus.txt(\" & ln & \"): got \" & gc & \" \" & go",
            "    end if",
            "end sub"]
    for c in cases:
        code = 0 if c["code"] == "OK" else CODES.index(c["code"])
        out.append("Expect( %s, %d, %d, %d )" % (call("TryFormat", c), code, c["off"], c["line"] + 1))
    out.append("print \"corpus: \" & passed & \" passed, \" & failed & \" failed\"")
    return "\n".join(out) + "\n"


def _radix(body, i, radix, maxd):
    v = d = 0
    while d < maxd and i < len(body):
        k = body[i]
        dv = -1
        if 48 <= k <= 57:
            dv = k - 48
        elif 97 <= k <= 122:
            dv = k - 87
        elif 65 <= k <= 90:
            dv = k - 55
        if dv < 0 or dv >= radix:
            break
        v = v * radix + dv
        i += 1
        d += 1
    return min(v, 255), i


def _escape(body, i):
    """support/text.tiko EscapeByteAt over a byte list, i at the backslash: (byte or -1, next i)."""
    i += 1
    if i >= len(body):
        return 92, i
    c = body[i]
    named = {97: 7, 98: 8, 102: 12, 110: 10, 114: 13, 116: 9, 118: 11, 92: 92, 34: 34, 39: 39}
    if c in named:
        return named[c], i + 1
    if 48 <= c <= 57:
        v = d = 0
        while d < 3 and i < len(body) and 48 <= body[i] <= 57:
            v = v * 10 + body[i] - 48
            i += 1
            d += 1
        return min(v, 255), i
    if c in (120, 88):
        return _radix(body, i + 1, 16, 2)
    if c == 38:
        if i + 1 < len(body):
            r = body[i + 1]
            if r in (104, 72):
                return _radix(body, i + 2, 16, 2)
            if r in (111, 79):
                return _radix(body, i + 2, 8, 3)
            if r in (98, 66):
                return _radix(body, i + 2, 2, 8)
        return -1, i + 1
    return c, i + 1


def value_units(lit):
    """The literal's run-time value as (unit, raw source char index) pairs -- formatcheck.tiko
    FcLiteral_'s rules -- or None where that cannot be reproduced."""
    prefix = 1 if lit[0] in "$!" else 0
    raw = lit[prefix + 1:-1]
    escaped = lit[0] == "!"
    body, at = [], []                  # bytes after '""' collapses, each with its raw char index
    k = 0
    while k < len(raw):
        for b in raw[k].encode("utf-8"):
            body.append(b)
            at.append(k)
        k += 2 if raw[k] == '"' and raw[k + 1:k + 2] == '"' else 1
    wide = False
    if escaped:
        q = 0
        while q < len(body) - 1:
            if body[q] == 92:
                if body[q + 1] in (117, 85):
                    wide = True
                q += 1
            q += 1
    items = []                         # (byte or None, unit or None, char index)
    p = 0
    while p < len(body):
        if not escaped or body[p] != 92:
            items.append((body[p], None, at[p]))
            p += 1
            continue
        nx = body[p + 1] if p + 1 < len(body) else 0
        if wide and nx in (117, 85):
            nd = 8 if nx == 85 else 4
            digits = bytes(body[p + 2:p + 2 + nd]).decode("latin-1")
            if len(digits) < nd or any(ch not in "0123456789abcdefABCDEF" for ch in digits):
                return None
            uv = int(digits, 16)
            if uv > 0x10FFFF:
                return None
            if uv > 0xFFFF:
                items.append((None, 0xD800 + ((uv - 0x10000) >> 10), at[p]))
                items.append((None, 0xDC00 + ((uv - 0x10000) & 0x3FF), at[p]))
            else:
                items.append((None, uv, at[p]))
            p += 2 + nd
            continue
        bv, np_ = _escape(body, p)
        if bv == 0:
            break
        if bv > 0:
            items.append((None, bv, at[p]) if wide else (bv, None, at[p]))
        p = np_
    out = []
    i = 0
    while i < len(items):
        b, u, a = items[i]
        if u is not None:
            out.append((u, a))
            i += 1
            continue
        n = 0 if b < 0x80 else 1 if 0xC2 <= b <= 0xDF else 2 if 0xE0 <= b <= 0xEF else 3 if 0xF0 <= b <= 0xF4 else -1
        if n < 0:
            return None
        seq = [b]
        for _ in range(n):
            i += 1
            if i >= len(items) or items[i][1] is not None or (items[i][0] & 0xC0) != 0x80:
                return None
            seq.append(items[i][0])
        i += 1
        try:
            cp = ord(bytes(seq).decode("utf-8"))
        except UnicodeDecodeError:
            return None
        if cp > 0xFFFF:
            out += [(0xD800 + ((cp - 0x10000) >> 10), a), (0xDC00 + ((cp - 0x10000) & 0x3FF), a)]
        else:
            out.append((cp, a))
    return out


def column(lit, off):
    """The 1-based column, in the generated line, of value offset 'off' of literal 'lit': the
    character its unit came from, or the closing quote past the last."""
    start = len("print strings.Format( ")
    prefix = 1 if lit[0] in "$!" else 0
    raw = lit[prefix + 1:-1]
    units = value_units(lit)
    k = units[off][1] if off < len(units) else len(raw)
    # Display columns, as the compiler's diagnostics count them (support/text.tiko
    # DisplayWidth): an East Asian wide character is two.
    return start + prefix + 2 + sum(2 if unicodedata.east_asian_width(ch) in "WF" else 1 for ch in raw[:k])


def compile_test(cases):
    src = ["'' GENERATED by tools/fmtcorpus/gen.py from tools/fmtcorpus/corpus.txt -- edit those, not this."]
    src += PRELUDE.rstrip("\n").split("\n")
    expects = []
    for c in cases:
        src.append("print " + call("Format", c))
        if c["code"] != "OK" and not c["run"]:
            assert value_units(c["lit"]) is not None, ("the compiler cannot check this literal: mark it run", c)
            expects.append("format-check.tiko(%d,%d): error %s: format string:"
                           % (len(src), column(c["lit"], c["off"]), TKO[c["code"]]))
    test = ["'' TKO0847..TKO0858: a LITERAL format string std/strings' Format would refuse at run time,",
            "'' refused when it is compiled -- the shared corpus (tools/fmtcorpus), whose run-time half is",
            "'' tests/std/format/corpus.test. Each refusal the compiler can see at the column of the",
            "'' library's offset; nothing for an accepted case or a refusal that only a value shows.",
            "'' GENERATED by tools/fmtcorpus/gen.py.",
            "'' TEST: cli",
            "'' ARGS: -fmax-errors=1000 -target windows-x86_64 tests/diagnostics/src/format-check.tiko -o tests/diagnostics/format-check.exe",
            "'' EXPECT-EXIT: 1"]
    test += ["'' EXPECT-OUT: " + e for e in expects]
    test.append("'' EXPECT-MAX-DIAG: %d" % len(expects))
    return "\n".join(src) + "\n", "\n".join(test) + "\n"


RUNTIME_TEST = """'' std/strings TryFormat over the shared format-string corpus (tools/fmtcorpus): every case's code
'' and offset. Its compile-time half is tests/diagnostics/format-check.test. GENERATED by
'' tools/fmtcorpus/gen.py.
'' TEST: cli
'' ARGS: -target windows-x86_64 tests/std/format/corpus.tiko -o tests/std/format/corpus.exe
'' ENV: TIKO_LIBPATH=toolchains/tiko-windows/lib/windows-x86_64
'' EXPECT-EXIT: 0
'' EXPECT-FILE: tests/std/format/corpus.exe
'' RUN: tests/std/format/corpus.exe
'' EXPECT-RUN-EXIT: 0
'' EXPECT-RUN-OUT: corpus: %d passed, 0 failed
"""


def write(path, text):
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote", path)


def main():
    argv = sys.argv[1:]
    lines, cases = load()
    if "--record" in argv:
        exe = argv[argv.index("--tiko") + 1]
        tmp = os.path.join(os.environ.get("TEMP", "/tmp"), "fmtcorpus_record")
        os.makedirs(tmp, exist_ok=True)
        write(os.path.join(tmp, "r.tiko"), runtime_test(cases))
        subprocess.run([exe, os.path.join(tmp, "r.tiko"), "-o", os.path.join(tmp, "r.exe")], check=True)
        res = subprocess.run([os.path.join(tmp, "r.exe")], capture_output=True, text=True).stdout
        for m in re.finditer(r"corpus\.txt\((\d+)\): got (\d+) (\d+)", res):
            n, gc, go = int(m.group(1)) - 1, int(m.group(2)), int(m.group(3))
            head, args, exp = [x.strip() for x in lines[n].rsplit("|", 2)]
            run = " run" if exp.strip().endswith(" run") else ""
            lines[n] = "%s | %s | %s" % (head, args, "OK" if gc == 0 else "%s %d%s" % (CODES[gc], go, run))
            print(("recorded line %d: %s" % (n + 1, lines[n])).encode("ascii", "backslashreplace").decode())
        write(CORPUS, "\n".join(lines))
        lines, cases = load()
    write("tests/std/format/corpus.tiko", runtime_test(cases))
    write("tests/std/format/corpus.test", RUNTIME_TEST % len(cases))
    src, test = compile_test(cases)
    write("tests/diagnostics/src/format-check.tiko", src)
    write("tests/diagnostics/format-check.test", test)


if __name__ == "__main__":
    main()
