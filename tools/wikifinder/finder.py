#!/usr/bin/env python3
"""Generate the wiki's Function Finder from areas.tsv and data/*.tsv.

    python tools/wikifinder/finder.py                  lint, then write the wiki
    python tools/wikifinder/finder.py --check          lint, and fail if any page is stale
    python tools/wikifinder/finder.py --lint [--area ID ...]
                                                       lint only (all areas, or the ones named); writes nothing

What it writes, all under wiki/:
  Function-Finder.md       the hub: one row per area
  <area page>.md           one finder page per area: task tables of Function, What it does, From
  Category-*.md            the source categories' API reference (or bare bullet list) becomes
                           the same task tables, between <!-- finder:start --> and <!-- finder:end -->
  <function page>.md       a missing or one-sentence lead under the title becomes its summary;
                           a lead of several sentences or lines is left as the author wrote it
  Keyword-Index.md         every A-Z entry gains its page's summary

Data, under tools/wikifinder/:
  areas.tsv                area and from rows
  data/<area>.tasks.tsv    task, ignore, seealso (and extra from) rows for one area
  data/<area>.tsv          function rows for one area:
      page       the wiki page the name links to, optionally Page#heading-anchor
      name       the name shown
      qualifier  shown after the name in parentheses, to tell two pages of one name apart; - for none
      task       a task id from the area's tasks file
      from       a value declared by a from row: built-in, std/strings, string.bi, ...
      rank       1-4 marks a "start with" pick on the hub; - for none
      summary    starts with a verb ("Returns", "Splits"), ends with a full stop, 90 characters at most

Edit the data, never the generated text.
"""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "data")
WIKI = os.path.normpath(os.path.join(HERE, "..", "..", "wiki"))
HUB = "Function-Finder"
INDEX = "Keyword-Index"
SUMMARY_MAX = 90
COLUMNS = ["page", "name", "qualifier", "task", "from", "rank", "summary"]
NOT_FUNCTIONS = {"Home", "Categories", INDEX, HUB}
MARKER = "<!-- Generated by tools/wikifinder/finder.py. Edit the data, not this page. -->"
START = "<!-- finder:start -->"
END = "<!-- finder:end -->"
FORBIDDEN = re.compile(r"FreeBASIC|\bfbc\b|QuickBASIC|\bQB\b|O\(|--|\|")
STRUCTURAL = re.compile(r"(#|```|\||- |\* |> |<|!\[)")

_pages = {}
_crlf = set()   # pages stored with CRLF; they are written back the same way


def read_page(page):
    if page not in _pages:
        path = os.path.join(WIKI, page + ".md")
        text = None
        if os.path.isfile(path):
            text = open(path, encoding="utf-8", newline="").read()
            if "\r\n" in text:
                _crlf.add(page)
                text = text.replace("\r\n", "\n")
        _pages[page] = text
    return _pages[page]


def base(page):
    return page.split("#", 1)[0]


def slug(heading):
    # GitHub's heading anchor: lower case, punctuation dropped, spaces to hyphens.
    return re.sub(r"[^\w\- ]", "", heading.strip().lower()).replace(" ", "-")


def headings(text):
    return {slug(h) for h in re.findall(r"^#{1,6} (.+?)\s*$", text, re.M)}


def links(text):
    return re.findall(r"\]\(([A-Za-z0-9_-]+)(?:#[^)]*)?\)", text)


def read_tsv(path):
    rows = []
    if not os.path.isfile(path):
        return None
    with open(path, encoding="utf-8") as f:
        for n, line in enumerate(f, 1):
            line = line.rstrip("\r\n")
            if not line.strip() or line.startswith("#"):
                continue
            rows.append((n, line.split("\t")))
    return rows


# ---------------------------------------------------------------- loading

class Data:
    def __init__(self):
        self.order = []
        self.areas = {}
        self.froms = {}
        self.tasks = {}
        self.ignore = {}
        self.seealso = {}
        self.rows = {}
        self.errors = []

    def err(self, msg):
        self.errors.append(msg)


def add_from(d, where, f):
    if len(f) != 4 or f[2] not in ("builtin", "import", "include"):
        d.err("%s: a from row is: from <value> builtin|import|include <module or ->" % where)
        return
    val = (f[2], f[3])
    if f[1] in d.froms and d.froms[f[1]] != val:
        d.err("%s: from %s is declared twice, differently" % (where, f[1]))
    d.froms[f[1]] = val


def load():
    d = Data()
    for n, f in read_tsv(os.path.join(HERE, "areas.tsv")):
        where = "areas.tsv:%d" % n
        if f[0] == "area" and len(f) == 6:
            aid, title, page, use, sources = f[1:]
            d.areas[aid] = {"title": title, "page": page, "use": use, "sources": sources.split()}
            d.order.append(aid)
            for s in d.areas[aid]["sources"]:
                if read_page(s) is None:
                    d.err("%s: source page %s does not exist" % (where, s))
        elif f[0] == "from":
            add_from(d, where, f)
        else:
            d.err("%s: not a valid area or from row" % where)

    for aid in d.order:
        tname = "data/%s.tasks.tsv" % aid
        trows = read_tsv(os.path.join(DATA, aid + ".tasks.tsv"))
        frows = read_tsv(os.path.join(DATA, aid + ".tsv"))
        if trows is None or frows is None:
            d.tasks[aid] = None
            d.rows[aid] = None
            continue
        d.tasks[aid], d.ignore[aid], d.seealso[aid] = [], {}, []
        for n, f in trows:
            where = "%s:%d" % (tname, n)
            if f[0] == "task" and len(f) == 3:
                if f[1] in [t for t, _ in d.tasks[aid]]:
                    d.err("%s: task id %s is used twice" % (where, f[1]))
                d.tasks[aid].append((f[1], f[2]))
            elif f[0] == "ignore" and len(f) == 3:
                d.ignore[aid][f[1]] = f[2]
            elif f[0] == "seealso" and len(f) == 3:
                d.seealso[aid].append((f[1], f[2]))
            elif f[0] == "from":
                add_from(d, where, f)
            else:
                d.err("%s: not a valid task, ignore, seealso or from row" % where)

        rows = []
        header = None
        for n, f in frows:
            where = "data/%s.tsv:%d" % (aid, n)
            if header is None:
                header = f
                if f != COLUMNS:
                    d.err("%s: header must be %s" % (where, "\t".join(COLUMNS)))
                continue
            if len(f) != len(COLUMNS):
                d.err("%s: %d columns, expected %d" % (where, len(f), len(COLUMNS)))
                continue
            r = dict(zip(COLUMNS, f))
            r["where"] = where
            r["area"] = aid
            rows.append(r)
        d.rows[aid] = rows
    return d


def all_rows(d):
    return [r for aid in d.order for r in (d.rows[aid] or [])]


# ---------------------------------------------------------------- lint

def lint(d, scope):
    for aid in scope:
        if d.rows[aid] is None:
            d.err("area %s: data/%s.tasks.tsv and data/%s.tsv are both required" % (aid, aid, aid))
    every = all_rows(d)
    listed = {base(r["page"]) for r in every}
    summaries = {}
    for r in every:
        p = base(r["page"])
        summaries.setdefault(p, set()).add(r["summary"])

    for aid in scope:
        if d.rows[aid] is None:
            continue
        task_ids = [t for t, _ in d.tasks[aid]]
        seen, ranks = set(), {}
        for r in d.rows[aid]:
            w = r["where"]
            text = read_page(base(r["page"]))
            if text is None:
                d.err("%s: page %s does not exist" % (w, base(r["page"])))
            elif "#" in r["page"] and r["page"].split("#", 1)[1] not in headings(text):
                d.err("%s: %s has no heading with anchor #%s" % (w, base(r["page"]), r["page"].split("#", 1)[1]))
            if r["task"] not in task_ids:
                d.err("%s: unknown task %s" % (w, r["task"]))
            if r["from"] not in d.froms:
                d.err("%s: from %s has no from row" % (w, r["from"]))
            key = (r["page"], r["name"], r["qualifier"], r["task"])
            if key in seen:
                d.err("%s: duplicate row for %s in task %s" % (w, r["page"], r["task"]))
            seen.add(key)
            s = r["summary"]
            if not re.match(r"[A-Z][a-z]+s\b", s):
                d.err("%s: summary must start with a verb such as 'Returns': %s" % (w, s))
            if not s.endswith("."):
                d.err("%s: summary must end with a full stop: %s" % (w, s))
            if len(s) > SUMMARY_MAX:
                d.err("%s: summary is %d characters, the limit is %d: %s" % (w, len(s), SUMMARY_MAX, s))
            if FORBIDDEN.search(s):
                d.err("%s: summary has a forbidden word or mark (%s): %s" % (w, FORBIDDEN.search(s).group(0), s))
            if not r["page"].startswith("Category-") and len(summaries[base(r["page"])]) > 1:
                d.err("%s: %s has different summaries in different rows" % (w, base(r["page"])))
            if not r["name"] or "|" in r["name"]:
                d.err("%s: name is empty or has a '|'" % w)
            if r["rank"] != "-":
                if r["rank"] not in ("1", "2", "3", "4"):
                    d.err("%s: rank must be 1-4 or -" % w)
                elif r["rank"] in ranks:
                    d.err("%s: rank %s is already used by %s" % (w, r["rank"], ranks[r["rank"]]))
                ranks[r["rank"]] = r["name"]
        for t, heading in d.tasks[aid]:
            if not any(r["task"] == t for r in d.rows[aid]):
                d.err("data/%s.tasks.tsv: task '%s' has no functions" % (aid, heading))
        if not ranks:
            d.err("data/%s.tsv: no row has a rank, so the hub has nothing to start with" % aid)
        for p, label in d.seealso[aid]:
            if read_page(base(p)) is None:
                d.err("data/%s.tasks.tsv: see-also page %s does not exist" % (aid, p))
        # Coverage: every function page the area's categories link to has a row somewhere.
        for src in d.areas[aid]["sources"]:
            text = read_page(src) or ""
            for p in dict.fromkeys(links(text)):
                if p in NOT_FUNCTIONS or p.startswith("Category-") or p.startswith("Functions-"):
                    continue
                if p in d.ignore[aid] or p in listed:
                    continue
                d.err("coverage: %s (linked from %s) has no row; add one to data/%s.tsv or an ignore row" % (p, src, aid))
                listed.add(p)


# ---------------------------------------------------------------- rendering

def from_cell(frm):
    return "built-in" if frm == "built-in" else "`%s`" % frm


def name_cell(r):
    cell = "[%s](%s)" % (r["name"], r["page"])
    if r["qualifier"] != "-":
        cell += " (%s)" % r["qualifier"]
    return cell


def from_note(d, frm):
    kind, module = d.froms[frm]
    if kind == "builtin":
        return "- **%s**: nothing; it is always available." % frm
    if kind == "include" and module != "-":
        return '- `%s`: `#include "%s"`, then `using %s`.' % (frm, frm, module)
    if kind == "include":
        return '- `%s`: `#include "%s"`.' % (frm, frm)
    if module == "-":
        return '- `%s`: `#import "%s"`.' % (frm, frm)
    return '- `%s`: `#import "%s"`, then `using %s` to call it by its bare name.' % (frm, frm, module)


def task_tables(d, aid, rows, level):
    out = []
    for t, heading in d.tasks[aid]:
        mine = [r for r in rows if r["task"] == t]
        if not mine:
            continue
        out += ["%s %s" % ("#" * level, heading), "", "| Function | What it does | From |", "|---|---|---|"]
        out += ["| %s | %s | %s |" % (name_cell(r), r["summary"], from_cell(r["from"])) for r in mine]
        out.append("")
    return out


def used_tasks(d, aid, rows):
    return [(t, h) for t, h in d.tasks[aid] if any(r["task"] == t for r in rows)]


def area_page(d, aid):
    a, rows = d.areas[aid], d.rows[aid]
    froms = list(dict.fromkeys(r["from"] for r in rows))
    froms.sort(key=lambda f: (d.froms[f][0] != "builtin", d.froms[f][0] == "include", f))
    out = ["[Home](Home) › [Function Finder](%s) › **%s**" % (HUB, a["title"]), ""]
    out += ["# %s" % a["title"], ""]
    out += ["The functions to %s, grouped by what you want to do. "
            "The **From** column says what a program needs before it can call one:" % a["use"], ""]
    # Three or more modules from one folder, each used by its own name, share one templated note.
    families = {}
    for f in froms:
        kind, module = d.froms[f]
        if kind == "import" and "/" in f and module == f.rsplit("/", 1)[1]:
            families.setdefault(f.rsplit("/", 1)[0], []).append(f)
    families = {k: v for k, v in families.items() if len(v) >= 3}
    notes = []
    for f in froms:
        fam = next((k for k, v in families.items() if f in v), None)
        if fam is None:
            notes.append(from_note(d, f))
        elif f == families[fam][0]:
            notes.append('- `%s/<Name>`: `#import "%s/<Name>"`, then `using <Name>` to call it by its bare name.' % (fam, fam))
    out += notes + [""]
    out += ["Jump to: " + " · ".join("[%s](#%s)" % (h, slug(h)) for _, h in used_tasks(d, aid, rows)), ""]
    out += task_tables(d, aid, rows, 2)
    if d.seealso[aid]:
        out += ["## See Also", ""] + ["- [%s](%s)" % (label, p) for p, label in d.seealso[aid]] + [""]
    out += ["---", "", "[Home](Home) · [Function Finder](%s) · [Keyword Index](%s)" % (HUB, INDEX), "", MARKER, ""]
    return "\n".join(out)


def category_titles():
    titles = {}
    for label, page in re.findall(r"\[([^\]]+)\]\((Category-[A-Za-z0-9_-]+)\)", read_page("Categories")):
        titles.setdefault(page, label)
    return titles


def hub_page(d):
    out = ["[Home](Home) › **Function Finder**", "", "# Function Finder", ""]
    out += ["Pick the area closest to what you want to do. An area's page groups its functions "
            "by task, with one line on what each one does. If you already know a function's name, "
            "the [Keyword Index](%s) lists every page from A to Z." % INDEX, ""]
    out += ["| Area | Use it to… | Start with |", "|---|---|---|"]
    for aid in d.order:
        a = d.areas[aid]
        picks = sorted((r for r in d.rows[aid] if r["rank"] != "-"), key=lambda r: r["rank"])
        out.append("| [**%s**](%s) | %s | %s |" % (a["title"], a["page"], a["use"],
                                                   " · ".join(name_cell(r) for r in picks)))
    out += ["", "---", "", "[Home](Home) · [All Categories](Categories) · [Keyword Index](%s)" % INDEX, "", MARKER, ""]
    return "\n".join(out)


# ---------------------------------------------------------------- category pages

def category_page(d, aid, cat):
    text = read_page(cat)
    a = d.areas[aid]
    member = set(links(text))
    rows = [r for r in d.rows[aid] if base(r["page"]) in member]
    if not rows:
        return None
    lines = text.split("\n")

    if START in lines and END in lines:
        s, e = lines.index(START), lines.index(END)
        region = lines[s + 1:e]
        api = any(l.strip() == "## API reference" for l in region)
    else:
        api_at = [i for i, l in enumerate(lines) if l.strip() == "## API reference"]
        if api_at:
            s = api_at[0]
            e = next((i for i in range(s + 1, len(lines)) if lines[i].strip() == "---" or lines[i].startswith("## ")), len(lines))
            api = True
        else:
            # The first bullet list of links after the title, before any section or rule.
            t = next(i for i, l in enumerate(lines) if l.startswith("# "))
            s = t + 1
            while s < len(lines) and not lines[s].startswith("- ["):
                if lines[s].startswith("## ") or lines[s].strip() == "---":
                    return None
                s += 1
            if s >= len(lines):
                return None
            e = s
            while e < len(lines) and lines[e].startswith("- ["):
                e += 1
            api = False
        region = lines[s:e]
        e -= 1  # the replacement below covers lines[s .. e] inclusive

    # Bullets in the old region that no row covers are kept, so nothing drops off the page.
    shown = {base(r["page"]) for r in rows}
    leftovers = [l for l in region if l.startswith("- [") and links(l) and links(l)[0] not in shown]

    body = []
    if api:
        body += ["## API reference", ""]
        body += ["Every entry, grouped by task. [%s](%s) lists them beside the rest of the area." % (a["title"], a["page"]), ""]
        body += task_tables(d, aid, rows, 3)
        if leftovers:
            body += ["### Also in this category", ""] + leftovers + [""]
    else:
        body += ["Grouped by task. [%s](%s) lists them beside the rest of the area." % (a["title"], a["page"]), ""]
        body += task_tables(d, aid, rows, 2)
        if leftovers:
            body += ["## Also in this category", ""] + leftovers + [""]
    rest = lines[e + 1:]
    if rest and rest[0].strip():
        rest = [""] + rest
    new = lines[:s] + [START, ""] + body + [END] + rest
    return "\n".join(new)


# ---------------------------------------------------------------- lead lines

def lead_page(page, summary):
    text = read_page(page)
    lines = text.split("\n")
    t = next((i for i, l in enumerate(lines) if l.startswith("# ")), None)
    if t is None:
        return None
    j = t + 1
    while j < len(lines) and not lines[j].strip():
        j += 1
    if j >= len(lines) or STRUCTURAL.match(lines[j]):
        lines[j:j] = [summary, ""]          # no lead at all: the summary becomes it
    elif j + 1 < len(lines) and lines[j + 1].strip():
        return None                         # a lead paragraph of several lines is the author's
    elif lines[j] != summary and re.search(r"[.!?]\s+[A-Z*`]", lines[j].strip()):
        return None                         # so is a lead of more than one sentence
    else:
        lines[j] = summary                  # one sentence or a fragment: the summary replaces it
    return "\n".join(lines)


def page_lead(text):
    lines = text.split("\n")
    t = next((i for i, l in enumerate(lines) if l.startswith("# ")), None)
    if t is None:
        return ""
    j = t + 1
    while j < len(lines) and not lines[j].strip():
        j += 1
    if j >= len(lines) or STRUCTURAL.match(lines[j]):
        return ""
    if j + 1 < len(lines) and lines[j + 1].strip():
        return ""
    s = lines[j].strip()
    if len(s) > 160 or not re.match(r"[A-Z`]", s) or re.search(r"O\(|--", s):
        return ""
    if not s.endswith((".", "?", "!", ")")):
        s += "."
    return s.replace("|", "\\|")


# ---------------------------------------------------------------- keyword index

BULLET = re.compile(r"^- \[(?P<name>.+?)\]\((?P<page>[^)]+)\)(?: — \*(?P<cat>.+)\*)?\s*$")
ROW = re.compile(r"^\| \[(?P<name>.+?)\]\((?P<page>[^)]+)\) \| (?P<sum>.*?) \| (?P<cat>.*?) \|\s*$")


def keyword_index(d, summaries, leads):
    text = read_page(INDEX)
    titles = category_titles()
    by_title = {v: k for k, v in titles.items()}
    out, entries, in_section = [], [], False

    def flush():
        if entries:
            out.extend(["| Name | What it does | Category |", "|---|---|---|"])
            for name, page, cat in entries:
                s = summaries.get(page) or leads.get(page, "")
                c = "[%s](%s)" % (cat, by_title[cat]) if cat in by_title else cat
                out.append("| [%s](%s) | %s | %s |" % (name, page, s, c))
            out.append("")
            entries.clear()

    for line in text.split("\n"):
        if line.startswith("## "):
            flush()
            in_section = True
            out.append(line)
            continue
        if in_section:
            m = BULLET.match(line) or ROW.match(line)
            if m:
                cat = m.group("cat") or ""
                cm = re.match(r"\[(.+?)\]\(.+?\)$", cat)
                entries.append((m.group("name"), m.group("page"), cm.group(1) if cm else cat))
                continue
            if line.startswith("| Name |") or line.startswith("|---"):
                continue
            if not line.strip() and entries:
                continue
            flush()
        out.append(line)
    flush()
    return "\n".join(out)


# ---------------------------------------------------------------- main

def generate(d):
    pages = {HUB: hub_page(d)}
    for aid in d.order:
        pages[d.areas[aid]["page"]] = area_page(d, aid)
    for aid in d.order:
        for cat in d.areas[aid]["sources"]:
            new = category_page(d, aid, cat)
            if new is not None:
                pages[cat] = new
    summaries = {}
    for r in all_rows(d):
        p = base(r["page"])
        if not p.startswith("Category-"):
            summaries.setdefault(p, r["summary"])
    for p, s in summaries.items():
        new = lead_page(p, s)
        if new is not None:
            pages[p] = new
    # The index reads every page's lead after the rewrite above.
    leads = {}
    for f in os.listdir(WIKI):
        if f.endswith(".md"):
            p = f[:-3]
            leads[p] = page_lead(pages.get(p) or read_page(p))
    pages[INDEX] = keyword_index(d, summaries, leads)
    return pages


def main():
    argv = sys.argv[1:]
    check, lint_only = "--check" in argv, "--lint" in argv
    scope_ids = [argv[i + 1] for i, a in enumerate(argv) if a == "--area" and i + 1 < len(argv)]
    d = load()
    for aid in scope_ids:
        if aid not in d.areas:
            d.err("--area %s: no such area" % aid)
    scope = [a for a in scope_ids if a in d.areas] or d.order
    if not d.errors:
        lint(d, scope)
    if d.errors:
        for e in d.errors:
            print(e, file=sys.stderr)
        print("%d problem(s); nothing written" % len(d.errors), file=sys.stderr)
        return 1
    count = sum(len(d.rows[a]) for a in scope)
    if lint_only:
        print("lint clean: %d rows in %s" % (count, ", ".join(scope)))
        return 0

    pages = generate(d)
    stale = 0
    for page, text in pages.items():
        if read_page(page) == text:
            continue
        if check:
            print("stale: wiki/%s.md" % page, file=sys.stderr)
        else:
            with open(os.path.join(WIKI, page + ".md"), "w", encoding="utf-8", newline="\n") as f:
                f.write(text.replace("\n", "\r\n") if page in _crlf else text)
        stale += 1
    print("%d rows in %d areas; %d page(s) %s" % (count, len(scope), stale, "stale" if check else "written"))
    return 1 if (check and stale) else 0


if __name__ == "__main__":
    sys.exit(main())
