#!/usr/bin/env python3
"""Generate wiki/Compiler-Error-Messages.md from tiko's diagnostic table.

Every message the compiler can emit is one DIAG( ) row in src/diag/diagids.ti, and nothing
else in the compiler may invent one. So the wiki's reference page is that table, rendered --
never a hand-kept list that drifts.

    python tools/wikidiag/gen.py            write the page
    python tools/wikidiag/gen.py --check    exit 1 if the page is out of date

The page follows the wiki's rules: it describes tiko on its own terms, with no dates,
commit hashes or local paths, so regenerating it at an unchanged table changes nothing.
"""
from __future__ import annotations

import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
TABLE = ROOT / "src" / "diag" / "diagids.ti"
PAGE = ROOT / "wiki" / "Compiler-Error-Messages.md"

DIAG_RE = re.compile(r'DIAG\(\s*(TKO\d{4})\s*,\s*SEV_(\w+)\s*,\s*"((?:[^"]|"")*)"\s*\)')

# The ranges diagids.ti's own header documents.
RANGES = [
    (1, 99, "Source and file handling"),
    (100, 199, "Driver and command line"),
    (200, 299, "Lexer"),
    (300, 399, "Preprocessor"),
    (400, 599, "Parser"),
    (600, 899, "Semantic analysis"),
    (900, 989, "Semantic analysis, continued, and notes"),
    (990, 999, "Compiler limits and internal errors"),
    (1000, 1049, "Interfaces"),
    (1050, 1099, "String slices"),
]


def cell(msg: str) -> str:
    """One message as a Markdown table cell: %N becomes a placeholder, and every character
    GitHub's renderer would read as markup is escaped."""
    msg = msg.replace('""', '"')
    out = []
    i = 0
    while i < len(msg):
        c = msg[i]
        if c == "%" and i + 1 < len(msg) and msg[i + 1].isdigit():
            out.append(f"‹arg{int(msg[i + 1]) + 1}›")
            i += 2
            continue
        if c in "\\`*_[]|":
            out.append("\\" + c)
        elif c == "<":
            out.append("&lt;")
        elif c == ">":
            out.append("&gt;")
        else:
            out.append(c)
        i += 1
    return "".join(out)


def render(rows: list[tuple[str, str, str]]) -> str:
    by_sev: dict[str, int] = {}
    for _, sev, _ in rows:
        by_sev[sev.lower()] = by_sev.get(sev.lower(), 0) + 1

    def count(sev: str) -> str:
        n = by_sev.get(sev, 0)
        return f"{n} {sev}{'s' if n != 1 else ''}"

    lines = [
        "[Home](Home) › **Compiler Error Messages**",
        "",
        "# Compiler Error Messages",
        "",
        "<!-- GENERATED by tools/wikidiag/gen.py from src/diag/diagids.ti. Do not edit by hand. -->",
        "",
        f"Every diagnostic the compiler can emit: {len(rows)} in all, "
        f"{count('error')}, {count('warning')} and {count('note')}.",
        "",
        "## Reading a diagnostic",
        "",
        "Each one names the file, the line and the column, its severity and its id, then shows the line with a caret under the column:",
        "",
        "```",
        "prog.tiko(1,16): error TKO0653: 'x' and its initializer disagree about being a string",
        "     |",
        "   1 | dim as integer x = \"a\"",
        "     |                ^",
        "```",
        "",
        "`--diagnostics-format gnu` writes the same diagnostic as `prog.tiko:1:16: error: ... [TKO0653]`, the form most editors match.",
        "",
        "- An **error** stops the build: nothing is linked, and the compiler exits with status 1.",
        "- A **warning** does not. `-Wno-TKOnnnn` suppresses one id, and `-Werror` turns every warning into an error.",
        "- A **note** follows an error or a warning and points at something related: where a name was first declared, or which instantiation of a generic produced the error.",
        "",
        "`tiko check` reports every diagnostic a build would, without writing an object or linking. `--diagnostics-file <path>` also writes each one to a tab-separated file, for editors and scripts.",
        "",
        "A diagnostic's number never changes. A retired diagnostic keeps its row rather than giving its number to another, so an id in an old build log still means what it meant then.",
        "",
        "In the tables, ‹arg1›, ‹arg2› … mark where the compiler substitutes a name, a type or a path.",
        "",
        "The **Compiler limits and internal errors** range is the compiler reporting on itself. An *internal compiler error* (TKO0993, TKO0994, TKO0995) is a bug in tiko, not in the program: the build stops rather than leave the construct out.",
        "",
        "Failures after code generation -- clang, the archiver, the linker, the resource compiler -- are reported under their own ids in the driver range (TKO0109 to TKO0116 among them).",
        "",
    ]

    seen = 0
    for lo, hi, title in RANGES:
        chunk = [(i, s, m) for (i, s, m) in rows if lo <= int(i[3:]) <= hi]
        if not chunk:
            continue
        seen += len(chunk)
        lines += [
            f"## {title} (TKO{lo:04d}–TKO{hi:04d})",
            "",
            "| Id | Severity | Message |",
            "| --- | --- | --- |",
        ]
        for ident, sev, msg in chunk:
            lines.append(f"| `{ident}` | {sev.lower()} | {cell(msg)} |")
        lines.append("")

    if seen != len(rows):
        sys.exit(f"wikidiag: {len(rows) - seen} rows fall outside every range -- add the new range to RANGES")

    lines += [
        "## See also",
        "",
        "- [Compatibility](Compatibility)",
        "- [Debugging](Debugging)",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="exit 1 if the page is out of date")
    args = ap.parse_args()

    rows = DIAG_RE.findall(TABLE.read_text(encoding="utf-8"))
    if len(rows) < 100:
        sys.exit(f"wikidiag: only {len(rows)} rows parsed -- the table's shape changed")
    ids = [r[0] for r in rows]
    if len(set(ids)) != len(ids):
        dup = sorted({i for i in ids if ids.count(i) > 1})
        sys.exit(f"wikidiag: duplicate ids in the table: {' '.join(dup)}")
    rows.sort(key=lambda r: int(r[0][3:]))

    page = render(rows)
    if args.check:
        cur = PAGE.read_text(encoding="utf-8") if PAGE.exists() else ""
        if cur != page:
            print(f"wikidiag: {PAGE.name} is out of date -- run tools/wikidiag/gen.py")
            return 1
        print(f"wikidiag: {PAGE.name} is current ({len(rows)} diagnostics)")
        return 0
    with open(PAGE, "w", encoding="utf-8", newline="\n") as f:
        f.write(page)
    print(f"wikidiag: wrote {PAGE.name} ({len(rows)} diagnostics)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
