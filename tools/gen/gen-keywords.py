#!/usr/bin/env python3
"""Regenerate src/lexer/keywords.ti from FreeBASIC's reserved-word vocabulary.

This reads the SPELLINGS and CLASSES of FreeBASIC's keywords -- the language's
vocabulary, which is also published in the manual's Alphabetical Keywords List. It
copies no code and reproduces no logic; the output is a sorted list of English words
and a class tag. Every entry is verified behaviourally by tests/lexer/keywords.test.

Run from the repository root:   python tools/gen/gen-keywords.py
"""
import re
import sys
from pathlib import Path

SOURCE = Path(r"C:\dev\fbc-modern\src\src\compiler\symb-keyword.bas")
OUTPUT = Path("src/lexer/keywords.ti")

CLASS_MAP = {
    "FB_TKCLASS_OPERATOR": "KWCLASS_OPERATOR",
    "FB_TKCLASS_KEYWORD":  "KWCLASS_KEYWORD",
    "FB_TKCLASS_QUIRKWD":  "KWCLASS_INTRINSIC",
}

ROW = re.compile(
    r'\(\s*@"([^"]*)"\s*,\s*FB_TK_\w+\s*,\s*(FB_TKCLASS_\w+)\s*'
    r'(?:,\s*([A-Za-z_|\s]+?))?\s*\)'
)


def main() -> int:
    if not SOURCE.exists():
        print(f"gen-keywords: {SOURCE} not found", file=sys.stderr)
        return 3

    text = SOURCE.read_text(encoding="utf-8", errors="replace")
    rows = ROW.findall(text)
    if not rows:
        print("gen-keywords: no rows matched -- the source format changed", file=sys.stderr)
        return 1

    seen, kept = {}, []
    for spelling, cls, opt in rows:
        opt = opt or ""
        if "QB_ONLY" in opt:
            continue                      # -lang qb only; tiko-lang targets -lang fb
        if spelling in seen:
            continue
        seen[spelling] = True
        kept.append((spelling, CLASS_MAP[cls]))

    kept.sort(key=lambda r: r[0])
    width = max(len(s) for s, _ in kept)

    out = []
    out.append("'' keywords.ti -- GENERATED by tools/gen/gen-keywords.py. Do not edit by hand.")
    out.append("''")
    out.append("'' FreeBASIC's reserved-word vocabulary: the spellings the lexer must recognise as")
    out.append("'' keyword tokens rather than identifiers, and the class each belongs to.")
    out.append("''")
    out.append("''   KWCLASS_OPERATOR    word-shaped operators: AND, MOD, SHL, NEW ...")
    out.append("''   KWCLASS_KEYWORD     ordinary keywords: DIM, IF, SUB, INTEGER ...")
    out.append("''   KWCLASS_INTRINSIC   the intrinsic statements: PRINT, OPEN, DRAW, PUT ...")
    out.append("''                       -- this is the registry of docs/plan/04 section 5.")
    out.append("''")
    out.append(f"'' {len(kept)} entries. QB-dialect-only spellings are excluded: tiko-lang is #lang \"fb\" only.")
    out.append("''")
    out.append("'' Words FBC-Modern adds CONTEXTUALLY -- defer, each, in, of, spawn -- are deliberately")
    out.append("'' absent. They are not reserved, so the lexer must keep treating them as identifiers.")
    out.append("")
    out.append("#ifndef __TKO_KEYWORDS_BI__")
    out.append("#define __TKO_KEYWORDS_BI__")
    out.append("")
    out.append("'' KW( enum name, spelling, class )")
    out.append("#macro TKO_KEYWORD_LIST( KW )")
    namew = width + 3
    for spelling, cls in kept:
        name = "KW_" + spelling
        out.append(f'    KW( {(name + ",").ljust(namew + 1)} "{spelling}",{" " * (width - len(spelling))} {cls} )')
    out.append("#endmacro")
    out.append("")
    out.append(f"const TKO_KEYWORD_COUNT as long = {len(kept)}")
    out.append("")
    out.append("#endif")

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")

    counts = {}
    for _, cls in kept:
        counts[cls] = counts.get(cls, 0) + 1
    print(f"gen-keywords: wrote {OUTPUT} -- {len(kept)} entries {counts}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
