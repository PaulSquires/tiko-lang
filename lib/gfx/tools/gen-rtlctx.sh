#!/bin/sh
# gen-rtlctx.sh -- generate abi/rtlctx-offsets.bi from the measured goldens.
#
# ORIGINAL WORK. Part of libtkogfx (LGPL-2.1-or-later with the static-linking
# exception).
#
# WHY THIS IS GENERATED RATHER THAN MIRRORED
#
# libtkogfx needs exactly two things out of FB_RTLIB_CTX: the offset of the hook
# table, and the offset of the exit_gfxlib2 callback. Mirroring the struct to
# reach them would mean mirroring FB_FILE -- FB_RTLIB_CTX is 20872 bytes on x64
# and `exit_gfxlib2` sits at offset 20864, behind a ~20KB file-handle array that
# is large, volatile, and none of our business. So we mirror the small structs
# (abi/rtlabi.bi) and GENERATE these two numbers instead.
#
# The generated file is checked in so a build does not require clang, and
# tools/gate-abi.sh re-generates and diffs it so it cannot go stale silently.
#
# Usage: tools/gen-rtlctx.sh [outfile]   (default: abi/rtlctx-offsets.bi)

set -e

HERE=$( cd "$( dirname "$0" )" && pwd )
GFX=$( dirname "$HERE" )
GOLD="$GFX/abi/offsets"
OUT="${1:-$GFX/abi/rtlctx-offsets.bi}"

field( ) {   # field <target> <name>
    awk -v f=".$2" '$1=="FB_RTLIB_CTX" && $2==f {
        for (i=3;i<=NF;i++) if (substr($i,1,4)=="off=") { print substr($i,5); exit }
    }' "$GOLD/$1.txt"
}

for t in win64 win32; do
    [ -f "$GOLD/$t.txt" ] || { echo "gen-rtlctx: no golden for $t" >&2; exit 3; }
done

H64=$( field win64 hooks );  E64=$( field win64 exit_gfxlib2 )
H32=$( field win32 hooks );  E32=$( field win32 exit_gfxlib2 )

for v in "$H64" "$E64" "$H32" "$E32"; do
    case "$v" in
        ''|*[!0-9]*) echo "gen-rtlctx: could not read an offset from the goldens" >&2; exit 3 ;;
    esac
done

cat > "$OUT" <<EOF
'' rtlctx-offsets.bi -- GENERATED by tools/gen-rtlctx.sh. DO NOT EDIT.
''
'' ORIGINAL WORK. Part of libtkogfx: LGPL-2.1-or-later with the static-linking
'' exception.
''
'' Byte offsets into the runtime's FB_RTLIB_CTX, measured by tools/probe-rtlabi.c
'' and regenerated from abi/offsets/*.txt. We do not mirror that struct: it is
'' over 20KB of mostly FB_FILE, and we need exactly these two numbers.
''
'' Regenerate:  tools/gen-rtlctx.sh
'' Verify:      tools/gate-abi.sh   (fails the build if this file is stale)

#pragma once

namespace TkoAbi

#if defined( __FB_64BIT__ )
    const RTLCTX_HOOKS_OFS   = $H64
    const RTLCTX_EXITGFX_OFS = $E64
#else
    const RTLCTX_HOOKS_OFS   = $H32
    const RTLCTX_EXITGFX_OFS = $E32
#endif

end namespace
EOF

echo "gen-rtlctx: wrote $OUT (hooks=$H64/$H32 exit_gfxlib2=$E64/$E32)"
