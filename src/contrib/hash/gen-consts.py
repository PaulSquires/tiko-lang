"""Generates pkg/std/hash/hashconsts.tiko: the MD5, SHA-1 and SHA-2 constants, from their definitions.

    python src/contrib/hash/gen-consts.py > pkg/std/hash/hashconsts.tiko

  MD5     K[i] = floor( abs( sin( i + 1 ) ) * 2^32 )                         (RFC 1321 3.4)
  SHA-256 K = first 32 bits of the fractional parts of the cube roots of the first 64 primes;
          H0 = ... of the square roots of the first 8 primes; SHA-224 H0 = bits 33..64 of the
          square roots of the 9th..16th primes                                (FIPS 180-4 4.2.2, 5.3)
  SHA-512 K = first 64 bits of the fractional parts of the cube roots of the first 80 primes;
          H0 = ... square roots of the first 8 primes; SHA-384 H0 = ... of the 9th..16th
                                                                              (FIPS 180-4 4.2.3, 5.3)
Integer roots are exact (Python ints); each table is checked against its first published value.
"""
import math, sys

def primes(n):
    out, k = [], 2
    while len(out) < n:
        if all(k % p for p in out if p * p <= k):
            out.append(k)
        k += 1
    return out

def iroot(x, r):
    lo, hi = 0, 1 << ((x.bit_length() // r) + 2)
    while lo < hi:
        mid = (lo + hi + 1) // 2
        if mid ** r <= x:
            lo = mid
        else:
            hi = mid - 1
    return lo

def frac_bits(p, r, bits):
    return iroot(p << (r * bits), r) & ((1 << bits) - 1)

P = primes(80)
md5k = [int(abs(math.sin(i + 1)) * 2 ** 32) & 0xFFFFFFFF for i in range(64)]
k256 = [frac_bits(p, 3, 32) for p in P[:64]]
h256 = [frac_bits(p, 2, 32) for p in P[:8]]
h224 = [frac_bits(p, 2, 64) & 0xFFFFFFFF for p in P[8:16]]
k512 = [frac_bits(p, 3, 64) for p in P[:80]]
h512 = [frac_bits(p, 2, 64) for p in P[:8]]
h384 = [frac_bits(p, 2, 64) for p in P[8:16]]

assert md5k[0] == 0xD76AA478 and k256[0] == 0x428A2F98 and h256[0] == 0x6A09E667
assert h224[0] == 0xC1059ED8 and k512[0] == 0x428A2F98D728AE22 and h512[0] == 0x6A09E667F3BCC908
assert h384[0] == 0xCBBB9D5DC1059ED8 and k512[79] == 0x6C44198C4A475817

def table(name, typ, vals, width, per):
    rows = [", ".join(f"&h{v:0{width}X}" + ("ull" if width == 16 else "") for v in vals[i:i + per])
            for i in range(0, len(vals), per)]
    return f"dim shared as {typ} {name}( 0 to {len(vals) - 1} ) = {{ _\n" + ", _\n".join("    " + r for r in rows) + " }\n"

out = ['#module "hash"',
       "'' std/hash: MD5, SHA-1 and SHA-2 constants -- GENERATED by src/contrib/hash/gen-consts.py from",
       "'' their definitions (RFC 1321, FIPS 180-4); do not edit.", "",
       table("HashMd5K", "ulong", md5k, 8, 8),
       table("HashSha256K", "ulong", k256, 8, 8),
       table("HashSha256H0", "ulong", h256, 8, 8),
       table("HashSha224H0", "ulong", h224, 8, 8),
       table("HashSha512K", "ulongint", k512, 16, 4),
       table("HashSha512H0", "ulongint", h512, 16, 4),
       table("HashSha384H0", "ulongint", h384, 16, 4)]
sys.stdout.write("\n".join(out))
