"""Generates pkg/std/hash/hashtables.tiko: the two reflected CRC-32 tables std/hash uses.

    python src/contrib/hash/gen-crc.py > pkg/std/hash/hashtables.tiko

IEEE 802.3 (poly 0xEDB88320, zlib/PNG/gzip) and Castagnoli (poly 0x82F63B78, iSCSI/ext4/SSE4.2).
Self-checks the check value of "123456789" for each before writing anything.
"""
import sys

def table(poly):
    t = []
    for i in range(256):
        c = i
        for _ in range(8):
            c = (c >> 1) ^ poly if c & 1 else c >> 1
        t.append(c)
    return t

def crc(t, data):
    c = 0xFFFFFFFF
    for b in data:
        c = t[(c ^ b) & 0xFF] ^ (c >> 8)
    return c ^ 0xFFFFFFFF

ieee, cast = table(0xEDB88320), table(0x82F63B78)
assert crc(ieee, b"123456789") == 0xCBF43926
assert crc(cast, b"123456789") == 0xE3069283

out = ['#module "hash"',
       "'' std/hash: the CRC-32 lookup tables -- GENERATED by src/contrib/hash/gen-crc.py, do not edit.",
       "'' IEEE (0xEDB88320) and Castagnoli (0x82F63B78), reflected, 256 entries each.", ""]
for name, t in (("HashCrcIeee", ieee), ("HashCrcCastagnoli", cast)):
    out.append(f"dim shared as ulong {name}( 0 to 255 ) = {{ _")
    rows = [", ".join(f"&h{v:08X}" for v in t[i:i + 8]) for i in range(0, 256, 8)]
    out.append(", _\n".join("    " + r for r in rows) + " }")
    out.append("")
sys.stdout.write("\n".join(out))
