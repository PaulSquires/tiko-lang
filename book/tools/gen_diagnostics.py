#!/usr/bin/env python3
"""Generate appendices/B-diagnostics.md from tiko's diagnostic table.

Every message tiko can emit is one DIAG( ) row in src/diag/diagids.ti, and nothing else
in the compiler may invent one. So the appendix is that table, rendered -- never a
hand-maintained list that can drift.

    python tools/gen_diagnostics.py [--tiko-src C:/dev/tiko-lang]
"""
from __future__ import annotations

import argparse
import datetime
import pathlib
import re
import sys

import pin as pinlib

DIAG_RE = re.compile(r'DIAG\(\s*(TKO\d{4})\s*,\s*SEV_(\w+)\s*,\s*"((?:[^"]|"")*)"\s*\)')

# The ranges are documented in diagids.bi's own header.
RANGES = [
    (1, 99, "Source and file handling"),
    (100, 199, "Driver and command line"),
    (200, 299, "Lexer"),
    (300, 399, "Preprocessor"),
    (400, 599, "Parser"),
    (600, 899, "Semantic analysis"),
    (900, 989, "Notes"),
    (990, 999, "Compiler limits and internal errors"),
    (1000, 1049, "Interfaces"),
    (1050, 1099, "String slices"),
]


def render_message(msg: str) -> str:
    msg = msg.replace('""', '"')
    # %0..%2 are the arguments Report( ) substitutes.
    msg = re.sub(r"%([0-9])", lambda m: f"‹arg{int(m.group(1)) + 1}›", msg)
    return msg.replace("|", "\\|")


def main() -> int:
    here = pathlib.Path(__file__).resolve().parent.parent
    ap = argparse.ArgumentParser()
    pinlib.add_arguments(ap)
    ap.add_argument("--out", default=str(here / "src" / "appendix-B-diagnostics.md"))
    args = ap.parse_args()

    pin = pinlib.read_pin(args.tiko_src, args.rev, args.worktree)
    pinlib.announce(pin, "gen_diagnostics")
    rows = DIAG_RE.findall(pinlib.read_source(pin, "src/diag/diagids.ti"))
    if len(rows) < 100:
        sys.exit(f"gen_diagnostics: only {len(rows)} rows parsed at {pin.commit} -- the table's shape changed")

    by_sev: dict[str, int] = {}
    for _, sev, _ in rows:
        by_sev[sev] = by_sev.get(sev, 0) + 1

    lines = [
        "# Appendix B: Diagnostics {#app-diagnostics}",
        "",
        "<!-- GENERATED by tools/gen_diagnostics.py. Do not edit. -->",
        "",
        f"Every diagnostic the compiler can emit, as of the pinned version: {len(rows)} in all "
        + ", ".join(f"{n} {s.lower()}{'s' if n != 1 else ''}" for s, n in sorted(by_sev.items()))
        + ".",
        "",
        "A diagnostic's number is stable forever. Retiring one leaves its row in place rather "
        "than reusing the number, so an id in an old build log still means what it meant then. "
        "Suppress a warning with `-Wno-TKOnnnn`, and turn warnings into errors with `-Werror`.",
        "",
        "Text like ‹arg1› marks where the compiler substitutes a name, type or path.",
        "",
    ]

    for lo, hi, title in RANGES:
        chunk = [(i, s, m) for (i, s, m) in rows if lo <= int(i[3:]) <= hi]
        if not chunk:
            continue
        lines += [
            f"## {title} (TKO{lo:04d}–TKO{hi:04d}) {{#app-diag-{lo:04d}}}",
            "",
            "| Id | Severity | Message |",
            "|---|---|---|",
        ]
        for ident, sev, msg in chunk:
            lines.append(f"| `{ident}` | {sev.lower()} | {render_message(msg)} |")
        lines.append("")

    shown = sum(1 for (i, _, _) in rows if any(lo <= int(i[3:]) <= hi for lo, hi, _ in RANGES))
    if shown != len(rows):
        sys.exit(f"gen_diagnostics: {len(rows) - shown} rows fall outside every range -- add the new range to RANGES")

    lines += [
        f"<!-- {len(rows)} rows, generated {datetime.date.today().isoformat()} from "
        f"src/diag/diagids.ti at {pin.commit} -->",
        "",
    ]

    out = pathlib.Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"gen_diagnostics: wrote {out} ({len(rows)} diagnostics)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
